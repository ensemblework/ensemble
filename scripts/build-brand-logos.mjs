#!/usr/bin/env node
// Builds the connector logo modules for hub-web from the files in
// apps/hub-web/components/connectors/brands/ (manifest.json lists each file, its
// display fit and where it came from).
//
//   node scripts/build-brand-logos.mjs          write the two generated modules
//   node scripts/build-brand-logos.mjs --check  fail when they are out of date
//
// brand-index.generated.ts is small and loads with the page (names and fits);
// brand-images.generated.ts holds the images as data URIs and is loaded lazily,
// so pages pay for the pictures only when a logo is on screen.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dir = path.join(root, "apps/hub-web/components/connectors/brands");
const outIndex = path.join(root, "apps/hub-web/components/connectors/brand-index.generated.ts");
const outImages = path.join(root, "apps/hub-web/components/connectors/brand-images.generated.ts");
const check = process.argv.includes("--check");

const manifest = JSON.parse(fs.readFileSync(path.join(dir, "manifest.json"), "utf8"));
const MEDIA = { svg: "image/svg+xml", webp: "image/webp", png: "image/png" };

function minifySvg(text) {
  return text
    .replace(/<\?xml[^>]*\?>/g, "")
    .replace(/<!DOCTYPE[^>]*>/gi, "")
    .replace(/<!--[\s\S]*?-->/g, "")
    .replace(/<metadata[\s\S]*?<\/metadata>/gi, "")
    .replace(/<title>[\s\S]*?<\/title>/gi, "")
    .replace(/>\s+</g, "><")
    .replace(/\s{2,}/g, " ")
    .trim();
}

/** Percent-encodes only what a data URI needs, so SVG stays readable and smaller than base64. */
function svgDataUri(svg) {
  const encoded = svg
    .replace(/"/g, "'")
    .replace(/%/g, "%25")
    .replace(/#/g, "%23")
    .replace(/</g, "%3C")
    .replace(/>/g, "%3E")
    .replace(/\n/g, " ");
  return `data:image/svg+xml,${encoded}`;
}

const keys = Object.keys(manifest).sort();
const index = {};
const images = {};
for (const key of keys) {
  const entry = manifest[key];
  if (!/^[a-z0-9]+$/.test(key)) throw new Error(`Logo key "${key}" must be lowercase letters and digits.`);
  if (!entry.name || !entry.file || !["pad", "fill"].includes(entry.fit) || !entry.source) {
    throw new Error(`Logo "${key}" needs name, file, fit (pad or fill) and source.`);
  }
  const ext = path.extname(entry.file).slice(1);
  const media = MEDIA[ext];
  if (!media) throw new Error(`Logo "${key}": ${entry.file} is not svg, webp or png.`);
  const bytes = fs.readFileSync(path.join(dir, entry.file));
  if (ext === "svg") {
    const svg = minifySvg(bytes.toString("utf8"));
    if (!/^<svg[\s>]/.test(svg) || /<script|on[a-z]+=/i.test(svg)) throw new Error(`Logo "${key}": ${entry.file} is not a plain SVG.`);
    images[key] = svgDataUri(svg);
  } else {
    images[key] = `data:${media};base64,${bytes.toString("base64")}`;
  }
  index[key] = { name: entry.name, fit: entry.fit };
}

const header = `// Generated by scripts/build-brand-logos.mjs from components/connectors/brands/. Do not edit.
// Every logo is a trademark of its owner, shown only to name the service being connected
// (sources in brands/manifest.json).
`;
const indexText = `${header}
export type BrandFit = "pad" | "fill";

export const BRAND_INDEX: Readonly<Record<string, { name: string; fit: BrandFit }>> = ${JSON.stringify(index, null, 2)};
`;
const imagesText = `${header}
export const BRAND_IMAGES: Readonly<Record<string, string>> = {
${keys.map((key) => `  ${JSON.stringify(key)}: ${JSON.stringify(images[key])},`).join("\n")}
};
`;

if (check) {
  const stale = [
    [outIndex, indexText],
    [outImages, imagesText],
  ].filter(([file, text]) => !fs.existsSync(file) || fs.readFileSync(file, "utf8") !== text);
  if (stale.length) {
    console.error(`Out of date: ${stale.map(([file]) => path.relative(root, file)).join(", ")}. Run node scripts/build-brand-logos.mjs`);
    process.exit(1);
  }
  console.log(`Brand logos up to date (${keys.length}).`);
} else {
  fs.writeFileSync(outIndex, indexText);
  fs.writeFileSync(outImages, imagesText);
  const size = Buffer.byteLength(imagesText);
  console.log(`Wrote ${keys.length} logos (${Math.round(size / 1024)} KB of images).`);
}
